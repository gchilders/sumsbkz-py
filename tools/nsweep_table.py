#!/usr/bin/env python3
"""Table from the fixed-budget runs of tools/nsweep.py: paper/tables/nsweep.tex.

For each k and N: the number of runs in the budget, the entries m <= 16 improved, and,
for m in 1..4 and 5..16, the total excess sum (n_N(m) - min_N' n_N'(m)) over the
entries reached at every N.
"""

import glob
import json
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from tools.compare import load_current  # noqa: E402

HERE = os.path.join(os.path.dirname(__file__), "..")


def main():
    cur = load_current("normal")
    res = defaultdict(dict)
    for p in glob.glob(os.path.join(HERE, "paper/data/nsweep/k*-N*.json")):
        d = json.load(open(p))
        res[d["k"]][d["N"]] = d
    with open(os.path.join(HERE, "paper/tables/nsweep.tex"), "w") as f:
        f.write("% generated by tools/nsweep_table.py -- do not edit\n")
        f.write("\\begin{tabular}{rrrrrrrr}\n\\toprule\n"
                "$k$ & $N$ & $\\rho$ & runs & improved & $m\\le4$ reached & gap, $m\\le4$ & gap, $5\\le m\\le16$ \\\\\n\\midrule\n")
        for k in sorted(res):
            Ns = sorted(res[k])
            fr = {N: {int(m): n for m, n in res[k][N]["frontier"].items()} for N in Ns}
            for N in Ns:
                imp = sum(1 for m, n in fr[N].items() if m <= 16 and cur.get(k, m) is not None and n < cur.get(k, m))
                ex = []
                for lo, hi in ((1, 4), (5, 16)):
                    ms = [m for m in range(lo, hi + 1) if all(m in fr[M] for M in Ns)]
                    ex.append(str(sum(fr[N][m] - min(fr[M][m] for M in Ns) for m in ms)) if ms else "--")
                low = sum(1 for m in range(1, 5) if m in fr[N])
                f.write(f"{k if N == Ns[0] else ''} & {N} & {res[k][N]['radius']:g} & {len(res[k][N]['runs'])} & "
                        f"{imp} & {low} & {ex[0]} & {ex[1]} \\\\\n")
            if k != max(res):
                f.write("\\addlinespace\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    print("wrote paper/tables/nsweep.tex")


if __name__ == "__main__":
    main()
