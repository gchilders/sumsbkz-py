#!/usr/bin/env python3
"""Table of the move-set experiment (tools/moveset.py) -> paper/tables/moveset.tex.

For k = 20, 24, 28 (N = 60, three seeds) it compares, with the same starts and descent:
the whole sieve database; random and shortest samples of it of the size of method E's move set;
method E itself (from paper/data/ablation); random samples of 1/16 to 1/2 of the database; and
the whole database with the frontier updated only on the accepted path or at the end points.
Columns: mean number of moves, range of improved entries over the seeds, mean number of entries
reached, and for the equal-size comparison the mean excess n - n_table over the entries reached
by all of these variants in the same seed (mean and standard deviation over the seeds).
"""
import csv
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from tools.compare import load_current  # noqa: E402

HERE = os.path.join(os.path.dirname(__file__), "..")
CMP = ["full", "rand_E", "short_E", "E", "path", "ends"]
ROWS = [("full", "sieve database"), ("rand_E", "random sample, $|E|$"), ("short_E", "shortest $|E|$"),
        ("E", "BKZ-40 rows (E)"), ("frac_2", "random $1/2$"), ("frac_4", "random $1/4$"),
        ("frac_8", "random $1/8$"), ("frac_16", "random $1/16$"),
        ("path", "database, path only"), ("ends", "database, end points only")]


def E_frontier(k, s):
    fr = {}
    for r in csv.DictReader(open(os.path.join(HERE, f"paper/data/ablation/k{k}-s{s}.csv"))):
        if r["method"] == "E" and r["n"]:
            fr[int(r["m"])] = int(r["n"])
    return fr


def main():
    cur = load_current("normal")
    lines = ["% generated by tools/moveset_table.py -- do not edit", "\\begin{tabular}{llrrrr}", "\\toprule",
             "$k$ & move set & moves & improved & reached & excess \\\\", "\\midrule"]
    summary = {}
    for k in (20, 24, 28):
        runs = []
        for s in (1, 2, 3):
            d = json.load(open(os.path.join(HERE, f"paper/data/moveset/k{k}-s{s}.json")))
            V = {name: {int(m): n for m, n in v["frontier"].items()} for name, v in d["variants"].items()}
            V["E"] = E_frontier(k, s)
            sizes = {name: v["moves"] for name, v in d["variants"].items()}
            sizes["E"] = d["E_moves"]
            common = set.intersection(*(set(V[c]) for c in CMP)) & {m for m in range(1, 17) if cur.get(k, m)}
            runs.append((V, sizes, common))
        for i, (key, label) in enumerate(ROWS):
            imp = [sum(1 for m, n in V[key].items() if m <= 16 and cur.get(k, m) and n < cur.get(k, m))
                   for V, _, _ in runs]
            reach = [len([m for m in V[key] if m <= 16]) for V, _, _ in runs]
            size = np.mean([sz[key] for _, sz, _ in runs])
            if key in CMP:
                ex = [np.mean([V[key][m] - cur.get(k, m) for m in c]) for V, _, c in runs if c]
                exs = f"${np.mean(ex):.1f}\\pm{np.std(ex):.1f}$" if ex else "--"
            else:
                exs = "--"
            summary[f"{k}/{key}"] = {"improved": imp, "reached": reach, "moves": size}
            kk = f"{k} ({min(len(c) for _, _, c in runs)})" if i == 0 else ""
            rng = f"{min(imp)}" if min(imp) == max(imp) else f"{min(imp)}--{max(imp)}"
            lines.append(f"{kk} & {label} & {size:,.0f} & {rng} & {np.mean(reach):.1f} & {exs} \\\\")
        if k != 28:
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(HERE, "paper/tables/moveset.tex"), "w").write("\n".join(lines) + "\n")
    json.dump(summary, open(os.path.join(HERE, "paper/data/moveset_summary.json"), "w"), indent=1)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
