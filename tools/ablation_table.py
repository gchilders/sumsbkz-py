#!/usr/bin/env python3
"""Tables from the ablation runs (tools/ablation.py) and the sieve statistics (tools/dbstats.py).

    python tools/ablation_table.py

Reads paper/data/ablation/k*-s*.{csv,json} and paper/data/dbstats/*.json; writes
paper/tables/ablation.tex, paper/tables/dbstats.tex and macros in paper/tables/ablnumbers.tex.

For each k the common target set is the set of entries m <= 16 with a table value that
every method except B reached in every seed.  "excess" is the mean over that set of
n - (table value), averaged over the seeds; the spread is the standard deviation over seeds.
"""

import csv
import glob
import json
import os
import statistics
from collections import defaultdict

HERE = os.path.join(os.path.dirname(__file__), "..")
METHODS = "ABCDE"


WORDS = {2: "two", 3: "three", 4: "four", 5: "five"}


def main():
    stats = []
    summary = None
    for sub, name in (("ablation", "ablation.tex"), ("ablation70", "ablation70.tex")):
        st, sm = abl_table(sub, name)
        stats += st
        summary = summary or sm
    tables(stats, summary)


def abl_table(sub, name):
    rows = []
    for p in sorted(glob.glob(os.path.join(HERE, f"paper/data/{sub}/k*-s*.csv"))):
        rows += list(csv.DictReader(open(p)))
    stats = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(HERE, f"paper/data/{sub}/k*-s*.json")))]
    if not rows:
        return stats, None
    n = defaultdict(dict)        # (k, seed, method) -> {m: n}
    rec, secs = {}, defaultdict(list)
    for r in rows:
        k, s, meth, m = int(r["k"]), int(r["seed"]), r["method"], int(r["m"])
        if r["record"]:
            rec[(k, m)] = int(r["record"])
        if r["n"]:
            n[(k, s, meth)][m] = int(r["n"])
        if m == 1:
            secs[(k, meth)].append(float(r["seconds"]))
    ks = sorted({int(r["k"]) for r in rows})
    seeds = sorted({int(r["seed"]) for r in rows})
    out = []
    summary = defaultdict(list)
    for k in ks:
        targets = [m for m in range(1, 17) if (k, m) in rec and all(
            m in n[(k, s, meth)] for s in seeds for meth in "ACDE")]
        for meth in METHODS:
            imp = [sum(1 for m, v in n[(k, s, meth)].items() if (k, m) in rec and v < rec[(k, m)]) for s in seeds]
            reach = [sum(1 for m in n[(k, s, meth)] if (k, m) in rec) for s in seeds]
            exc = [statistics.mean(n[(k, s, meth)][m] - rec[(k, m)] for m in targets)
                   for s in seeds if targets and all(m in n[(k, s, meth)] for m in targets)]
            med = [statistics.median(n[(k, s, meth)][m] - rec[(k, m)] for m in targets)
                   for s in seeds if targets and all(m in n[(k, s, meth)] for m in targets)]
            t = statistics.mean(secs[(k, meth)])
            summary[meth].append((statistics.mean(imp), exc))
            out.append((k, meth, t, imp, reach, exc, med, len(targets)))
    with open(os.path.join(HERE, "paper/tables", name), "w") as f:
        f.write("% generated by tools/ablation_table.py -- do not edit\n")
        f.write("\\begin{tabular}{rlrrrrr}\n\\toprule\n"
                "$k$ & method & time (s) & improved & reached & excess & median \\\\\n\\midrule\n")
        last = None
        for k, meth, t, imp, reach, exc, med, nt in out:
            if last is not None and k != last:
                f.write("\\addlinespace\n")
            rng = f"{min(imp)}" if min(imp) == max(imp) else f"{min(imp)}--{max(imp)}"
            ex = (f"${statistics.mean(exc):.1f}\\pm{statistics.pstdev(exc):.1f}$" if exc else "--")
            kk = f"{k} ({nt})" if k != last else ""
            md = f"${statistics.mean(med):.1f}$" if med else "--"
            f.write(f"{kk} & {meth} & {t:.0f} & {rng} & {statistics.mean(reach):.1f} & {ex} & {md} \\\\\n")
            last = k
        f.write("\\bottomrule\n\\end{tabular}\n")
    return stats, (summary, ks, seeds)


def tables(stats, summ):
    summary, ks, seeds = summ
    # database statistics: the ablation lattices (N=60) and the dbstats runs (N=70)
    db = [(s["k"], s["N"], s["radius"], s["db"], s.get("descent_steps"), s["sieve_s"]) for s in stats]
    cmp = []
    for p in sorted(glob.glob(os.path.join(HERE, "paper/data/dbstats/*.json"))):
        d = json.load(open(p))
        db.append((d["k"], d["N"], d["radius"], d["progressive"]["db"], d["progressive"]["descent_steps"],
                   d["progressive"]["sieve_s"]))
        cmp.append(d)
    with open(os.path.join(HERE, "paper/tables/dbstats.tex"), "w") as f:
        f.write("% generated by tools/ablation_table.py -- do not edit\n")
        f.write("\\begin{tabular}{rrrrrrrrr}\n\\toprule\n"
                "$k$ & $N$ & $\\rho$ & size & out & $\\frac{\\max\\|c\\|^2}{\\GH^2}$ & $T$ med., max "
                "& $\\min(p,q)$ min, med. & sat.\\\\\n\\midrule\n")
        seen = set()
        for k, N, rho, d, st, ts in sorted(db, key=lambda t: (t[1], t[0])):
            if (k, N) in seen:
                continue
            seen.add((k, N))
            f.write(f"{k} & {N} & {rho:g} & {d['size']:,} & {100 * d['frac_outside_radius']:.0f}\\% & "
                    f"{d['norm2_over_gh2_q'][4]:.2f} & {d['T_q'][2]:.0f}, {d['max_T']} & "
                    f"{d['minpq_q'][0]:.0f}, {d['minpq_q'][2]:.0f} & {d['sat_achieved']:.2f} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")

    # macros
    allsteps = [s["descent_steps"] for s in stats] + [d["progressive"]["descent_steps"] for d in cmp] \
        + [d["random"]["descent_steps"] for d in cmp] + [s["E_descent_steps"] for s in stats]
    uns = sum(s["db"]["unsaturated"] for s in stats) + sum(d[v]["db"]["unsaturated"] for d in cmp for v in ("progressive", "random"))
    sieves = sum(s["db"]["sieves"] for s in stats) + sum(d[v]["db"]["sieves"] for d in cmp for v in ("progressive", "random"))
    fin = sum(s["db"]["final_unsaturated"] for s in stats) + sum(d[v]["db"]["final_unsaturated"] for d in cmp for v in ("progressive", "random"))
    nfin = len(stats) + 2 * len(cmp)
    with open(os.path.join(HERE, "paper/tables/ablnumbers.tex"), "w") as f:
        f.write("% generated by tools/ablation_table.py -- do not edit\n")
        f.write(f"\\newcommand{{\\AblK}}{{{', '.join(map(str, ks))}}}\n")
        f.write(f"\\newcommand{{\\AblSeeds}}{{{WORDS.get(len(seeds), len(seeds))}}}\n")
        f.write(f"\\newcommand{{\\StepsMax}}{{{max(s['max'] for s in allsteps)}}}\n")
        f.write(f"\\newcommand{{\\StepsMedian}}{{{statistics.median(s['median'] for s in allsteps):g}}}\n")
        f.write(f"\\newcommand{{\\StepsAtCap}}{{{sum(s['at_cap'] for s in allsteps)}}}\n")
        f.write(f"\\newcommand{{\\StepsTasks}}{{{sum(s['tasks'] for s in allsteps):,}}}\n")
        f.write(f"\\newcommand{{\\SatSieves}}{{{sieves:,}}}\n")
        f.write(f"\\newcommand{{\\SatFailed}}{{{uns}}}\n")
        f.write(f"\\newcommand{{\\SatFinalFailed}}{{{fin}}}\n")
        f.write(f"\\newcommand{{\\SatRuns}}{{{nfin}}}\n")
        for meth in METHODS:
            imps = [i for i, _ in summary[meth]]
            f.write(f"\\newcommand{{\\AblImp{meth}}}{{{sum(imps) / len(seeds) if seeds else 0:.0f}}}\n")
    # progressive vs random start
    with open(os.path.join(HERE, "paper/tables/progressive.tex"), "w") as f:
        f.write("% generated by tools/ablation_table.py -- do not edit\n")
        f.write("\\begin{tabular}{rrrrrrr}\n\\toprule\n& & \\multicolumn{2}{c}{sieve time (s)} & "
                "\\multicolumn{2}{c}{median $\\|c\\|^2/\\GH^2$} & \\\\\n\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\n"
                "$k$ & seed & progr. & random & progr. & random & $\\sum_m (n_{\\mathrm P}-n_{\\mathrm R})$ \\\\\n\\midrule\n")
        for d in cmp:
            P, R = d["progressive"], d["random"]
            common = [m for m in P["frontier"] if m in R["frontier"]]
            diff = sum(P["frontier"][m] - R["frontier"][m] for m in common)
            f.write(f"{d['k']} & {d['seed']} & {P['sieve_s']:.0f} & {R['sieve_s']:.0f} & "
                    f"{P['db']['norm2_over_gh2_q'][2]:.3f} & {R['db']['norm2_over_gh2_q'][2]:.3f} & ${diff:+d}$ \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    print("wrote ablation.tex, dbstats.tex, progressive.tex, ablnumbers.tex")


if __name__ == "__main__":
    main()
