#!/usr/bin/env python3
"""Contribution of each method to the improvements for 33 <= k <= 100 -> paper/tables/contrib.tex.

Every result file is assigned a method by tools/attribution.method_of: the sieve search (any N,
including repetitions), coset starts, descent from known identities, completions of
Wroblewski's congruence solutions, and completions of structured congruence solutions; combined
files are ignored.  For each method the table gives the entries (m <= 16) it improves, the entries
improved by it and by no other method, and the cumulative number improved when the methods are
added in the order listed, with the terms saved by the best identity found so far.
"""
import csv
import glob
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from eslp.solutions import read_solutions  # noqa: E402
from tools.attribution import method_of  # noqa: E402

HERE = os.path.join(os.path.dirname(__file__), "..")
ORDER = [("sieve", "sieve search"), ("coset", "coset starts"), ("recstart", "known-identity starts"),
         ("wcomplete", "Wr\\'oblewski completions"), ("struct", "structured completions")]


def klass(p):
    if "/recstart/" in p or "recstart-" in os.path.basename(p):
        return "recstart"
    m = method_of(p)
    return "sieve" if m.startswith("sieve") else m


def main():
    ref = {}
    for r in csv.DictReader(open(os.path.join(HERE, "archive/table_reference.csv"))):
        k, m = int(r["k"]), int(r["m"])
        if k >= 33:
            n = int(r["table_n"])
            if r["least_n_of_database_identity"]:
                n = min(n, int(r["least_n_of_database_identity"]))
            ref[(k, m)] = n
    best = {c: {} for c, _ in ORDER}
    for p in glob.glob(os.path.join(HERE, "results/**/*.txt"), recursive=True):
        c = klass(p)
        if c not in best:
            continue
        for s in read_solutions(p):
            key = (s.k, s.m)
            if key in ref and (key not in best[c] or s.n < best[c][key]) and s.is_valid():
                best[c][key] = s.n
    imp = {c: {key for key, n in b.items() if n < ref[key]} for c, b in best.items()}
    lines = ["% generated by tools/contrib.py -- do not edit", "\\begin{tabular}{lrrrr}", "\\toprule",
             "method & improves & only this & cumulative & terms saved \\\\", "\\midrule"]
    acc, bestacc, out = set(), {}, {}
    for c, label in ORDER:
        others = set().union(*(imp[d] for d, _ in ORDER if d != c))
        acc |= imp[c]
        for key, n in best[c].items():
            if n < bestacc.get(key, 10**12):
                bestacc[key] = n
        saved = sum(ref[key] - n for key, n in bestacc.items() if n < ref[key])
        out[c] = {"improves": len(imp[c]), "only": len(imp[c] - others), "cumulative": len(acc), "saved": saved}
        lines.append(f"{label} & {len(imp[c]):,} & {len(imp[c] - others):,} & {len(acc):,} & {saved:,} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(HERE, "paper/tables/contrib.tex"), "w").write("\n".join(lines) + "\n")
    json.dump(out, open(os.path.join(HERE, "paper/data/contrib.json"), "w"), indent=1)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
