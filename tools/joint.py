#!/usr/bin/env python3
"""Joint descent over a congruence part and its completion.

    python tools/joint.py -k 85 -M 128 -C 100 -N 100 --l-db results/complete/db-k85-N100.npy \
        -o results/complete/joint-k85-M128.txt

The identities sought are relations on the bases T u {M x : x <= N}, where T is the set of the
first C integers >= --start that are prime to M (so no base of T is a multiple of M).  These
relations form a lattice of rank C + N - 1 generated by two kinds of vectors:

  (0, w)    with w in L_{k,N}: the completion moves (the sieve database of L_{k,N});
  (u, c_u)  with u in Lambda = {u : sum u_t t^k == 0 mod M^k} and sum_x c_u,x x^k =
            -sum_t u_t t^k / M^k: lifted congruence moves.

Lifting is linear up to L_{k,N}: once each row R_i of a reduced basis of Lambda has a lift c_i
(from the embedding of tools/complete.particular), any u = a R has the lift a.(c_i), which is
then shortened by Babai's nearest-plane algorithm against a reduced basis of L_{k,N}.  The
descent of eslp/descent.py then runs on full vectors in Z^(C+N), with the lifted short vectors
of Lambda and the database of L_{k,N} as moves, so that the congruence part and the completion
change together.  Every identity is assembled, verified exactly and written out.
"""

from __future__ import annotations

import argparse
import multiprocessing
import os
import sys
import time

import numpy as np
from fpylll import GSO, IntegerMatrix

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from eslp.lattice import bkz, relation_basis  # noqa: E402
from eslp.solutions import Solution  # noqa: E402
from tools.compare import load_current  # noqa: E402
from tools.complete import particular  # noqa: E402
from tools.congsolve import candidates, congruence_basis, strong_moments  # noqa: E402


def _lift_row(args):
    D, k, N = args
    sols = particular(D, k, N)
    return sols[0] if sols else None


def babai_reduce(G, B, c):
    """c minus the lattice vector of B (with GSO G) that Babai's algorithm finds close to c."""
    coef = G.babai([int(v) for v in c])
    return np.asarray(c, dtype=np.int64) - np.array(B.multiply_left(coef), dtype=np.int64)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-k", type=int, required=True)
    ap.add_argument("-M", type=int, required=True)
    ap.add_argument("-C", type=int, default=100)
    ap.add_argument("--start", type=int, default=None, help="smallest candidate base (default 10 M + 1)")
    ap.add_argument("-N", type=int, default=100)
    ap.add_argument("--l-db", required=True, help="sieve database of L_{k,N} (.npy)")
    ap.add_argument("--alg", default="gpu", help="sieve and descent: gpu, or a CPU sieve (bgj1, bdgl)")
    ap.add_argument("--radius", type=float, default=4 / 3)
    ap.add_argument("--threads", type=int, default=os.cpu_count())
    ap.add_argument("--lifted", type=int, default=20000, help="number of short vectors of Lambda to lift")
    ap.add_argument("--starts", type=int, default=300)
    ap.add_argument("--mmax", type=int, default=40)
    ap.add_argument("--targets", default="auto",
                    help="comma-separated residues R: starts with D == R mod L, so that the completion has "
                         "first moment near R and leans to one side; 'auto' = -N/2 * (N, 2N, 4N, 8N)")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()
    k, M, C, N = a.k, a.M, a.C, a.N
    start = a.start or 10 * M + 1
    cur = load_current("normal")
    t0 = time.time()

    # Lambda: basis, reduction, sieve
    T = candidates(M, C, start)
    moments = strong_moments(k, N)
    import math
    Lmod = 1
    for _, mj in moments:
        Lmod = Lmod * mj // math.gcd(Lmod, mj)
    R = bkz(bkz(congruence_basis(T, k, M, moments), 20), 30)
    from eslp.sieve import sieve_db
    kw = dict(threads=a.threads, alg=a.alg, saturation_radius=a.radius)
    if a.alg == "gpu":
        kw.update(gpu_bucketer="bdgl", saturation_ratio=0.375, db_size_factor=2.77,
                  gpu_params={"multi_bucket": 2, "max_nr_buckets": 0})
    DL = sieve_db(R, **kw)
    sq = (DL.astype(np.int64) ** 2).sum(1)
    short = DL[np.argsort(sq, kind="stable")[: a.lifted]].astype(np.int64)
    print(f"k={k} M={M} C={C}: bases {T[0]}..{T[-1]}; moments {moments}; Lambda database {len(DL)}, lifting {len(short)} "
          f"({time.time() - t0:.0f}s)", flush=True)

    # lifts of the basis rows of Lambda (one embedding reduction each)
    Q = M**k
    tk = [t**k for t in T]
    Ds = []
    for r in R:
        S = sum(int(c) * v for c, v in zip(r, tk))
        assert S % Q == 0
        Ds.append(-(S // Q))
    t1 = time.time()
    with multiprocessing.get_context("spawn").Pool(a.threads) as P:
        lifts = P.map(_lift_row, [(D, k, N) for D in Ds])
    if any(x is None for x in lifts):
        raise RuntimeError("a basis row of Lambda could not be lifted")
    Lc = np.array(lifts, dtype=object)
    print(f"  lifted {len(R)} basis rows ({time.time() - t1:.0f}s)", flush=True)

    # Babai against a reduced basis of L_{k,N}
    RL = bkz(relation_basis(list(range(1, N + 1)), k), 20)
    BL = IntegerMatrix.from_matrix(RL.tolist())
    G = GSO.Mat(BL, float_type="mpfr")
    G.update_gso()
    Rf = R.astype(np.float64)

    def lift(u):
        aa = np.rint(np.linalg.solve(Rf.T, u.astype(np.float64))).astype(np.int64)
        if not np.array_equal(aa @ R, u):
            return None
        c = (aa.astype(object) @ Lc)
        return babai_reduce(G, BL, c)

    t1 = time.time()
    moves_up = []
    for u in np.concatenate([R, short]):
        c = lift(u)
        if c is None or np.abs(c).max() > 32000:
            continue
        moves_up.append(np.concatenate([u, c]))
    moves_up = np.array(moves_up, dtype=np.int16)
    print(f"  {len(moves_up)} lifted congruence moves, median |c| {np.median(np.abs(moves_up[:, C:]).sum(1)):.0f} "
          f"({time.time() - t1:.0f}s)", flush=True)

    # completion moves, padded on the T coordinates
    D0 = np.load(a.l_db)
    if D0.shape[1] != N:
        raise ValueError("database dimension does not match N")
    moves = np.concatenate([moves_up, np.concatenate([np.zeros((len(D0), C), dtype=np.int16),
                                                       D0.astype(np.int16)], axis=1)])
    # affine starts: congruence parts u0 with M^k | sum u0 t^k and D(u0) = -sum u0 t^k / M^k == R
    # (mod Lmod), shortened against Lambda; their completions have first moment near R
    targets = ([-(N // 2) * f * N for f in (1, 2, 4, 8)] if a.targets == "auto"
               else [int(x) for x in a.targets.split(",")])
    Qp = M**k * Lmod
    from fpylll import FPLLL
    BLam = IntegerMatrix.from_matrix(R.tolist())
    affine = []
    i1 = next(i for i, t in enumerate(T) if math.gcd(t, Qp) == 1)
    inv = pow(pow(T[i1], k, Qp), -1, Qp)
    for Rt in targets:
        u = np.zeros(C, dtype=object)
        u[i1] = (-(M**k) * Rt * inv) % Qp
        old = FPLLL.get_precision()
        FPLLL.set_precision(max(53, int(u[i1]).bit_length() + 64))
        try:
            GL = GSO.Mat(BLam, float_type="mpfr")
            GL.update_gso()
            for _ in range(3):
                coef = GL.babai([int(v) for v in u])
                close = np.array(BLam.multiply_left(coef), dtype=object)
                if not any(close):
                    break
                u = u - close
        finally:
            FPLLL.set_precision(old)
        S = sum(int(c) * t**k for c, t in zip(u, T))
        assert S % M**k == 0 and (-(S // M**k) - Rt) % Lmod == 0
        sols = particular(-(S // M**k), k, N)
        if sols and max(abs(int(v)) for v in u) < 2**31:
            affine.append(np.concatenate([np.array([int(v) for v in u], dtype=np.int64),
                                          np.array([int(v) for v in sols[0]], dtype=np.int64)]))
            print(f"  target R={Rt}: congruence part {int(sum(abs(int(v)) for v in u))} terms, completion "
                  f"{int(sum(abs(int(v)) for v in sols[0]))} terms, first moment "
                  f"{sum(int(v) * x for x, v in enumerate(sols[0], 1))}", flush=True)

    # starts: the frontier of a descent inside Lambda (congruence parts with a small side), lifted,
    # and some random lifted congruence moves
    rng = np.random.default_rng(k * 1000 + M)
    lstarts = np.concatenate([R, DL[rng.permutation(len(DL))[:300]].astype(np.int64)])
    t1 = time.time()
    if a.alg == "gpu":
        from eslp.descent_gpu import descend_gpu
        frl = descend_gpu(lstarts, DL)
    else:
        from eslp.descent import descend
        frl = descend(lstarts, DL)
    inner = []
    for m, (n, u) in sorted(frl.items()):
        if m <= 40:
            c = lift(np.asarray(u, dtype=np.int64))
            if c is not None and np.abs(c).max() <= 32000:
                inner.append(np.concatenate([np.asarray(u, dtype=np.int64), c]))
    print(f"  descent inside Lambda: small sides {[m for m in sorted(frl) if m <= 40][:12]}..., "
          f"{len(inner)} lifted starts ({time.time() - t1:.0f}s)", flush=True)
    A0 = np.array(affine, dtype=np.int64).reshape(-1, C + N)
    shifts = moves_up[rng.permutation(len(moves_up))[: a.starts]].astype(np.int64)
    starts = np.concatenate([A0] + [a0[None, :] + shifts[: a.starts // max(1, len(A0))] for a0 in A0]
                            + [np.array(inner, dtype=np.int64).reshape(-1, C + N)])

    t1 = time.time()
    if a.alg == "gpu":
        from eslp.descent_gpu import descend_gpu
        fr = descend_gpu(starts, moves)
    else:
        from eslp.descent import descend
        fr = descend(starts, moves)
    print(f"  descent over {len(moves)} moves from {len(starts)} starts ({time.time() - t1:.0f}s)", flush=True)

    print("  smallest sides reached (m:n): " + " ".join(f"{m}:{n}" for m, (n, _) in sorted(fr.items())[:10]), flush=True)
    bases = list(T) + [M * x for x in range(1, N + 1)]
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    cells = []
    with open(a.out, "a") as f:
        f.write(f"// joint k={k} M={M} C={C} start={start} N={N} {time.strftime('%Y-%m-%d %H:%M')}\n")
        for m, (n, v) in sorted(fr.items()):
            if m > a.mmax:
                continue
            s = Solution(k, {b: int(c) for b, c in zip(bases, v) if c}).normalized()
            if not s.is_valid():
                raise AssertionError(f"joint identity fails verification k={k} m={m}")
            r = cur.get(k, s.m)
            tag = f" // NEW record (was {r})" if r is not None and s.n < r else ""
            f.write(f"{s.format()}{tag} [joint M={M} C={C}]\n")
            if s.m <= 16:
                cells.append(f"{s.m}:{s.n}" + ("" if r is None else ("<%d!" % r if s.n < r else "/%d" % r)))
    print(f"  k={k:3d}  " + "  ".join(cells) + f"   ({time.time() - t0:.0f}s)", flush=True)


if __name__ == "__main__":
    main()
