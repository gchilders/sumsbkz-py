#!/usr/bin/env python3
"""The congruence obstruction for each power: paper/tables/congruence.tex and macros.

    python tools/congruence.py [-N 100]

If p is prime and (p-1) | (k-j) with 1 <= j < k, then x^k == x^j (mod p) for every integer x,
so every relation c of L_{k,N} satisfies sum_x c_x x^j == 0 (mod M_j(k)), where M_j(k) is the
product of these primes.  A relation with T terms and bases at most N has
|sum_x c_x x^j| <= T N^j, so when M_j(k) > T N^j the moment sum_x c_x x^j vanishes.  We take for
T the bound sqrt(N) GH(L_{k,N}) on the number of terms of a relation of Gaussian-heuristic
length, and report, for each k, the j maximizing r_j = M_j(k) / (T N^j), together with the
number of entries m <= 16 improved by the N = 100 searches and by the completions.
"""

from __future__ import annotations

import argparse
import glob
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from eslp.solutions import read_solutions  # noqa: E402
from tools.compare import load_current  # noqa: E402

HERE = os.path.join(os.path.dirname(__file__), "..")
PRIMES = [p for p in range(2, 500) if all(p % q for q in range(2, int(p**0.5) + 1))]


def M(k, j):
    return math.prod(p for p in PRIMES if (k - j) % (p - 1) == 0)


def gh2(k, N):
    d = N - 1
    logdet = 0.5 * math.log(sum(x ** (2 * k) for x in range(1, N + 1)))
    return d / (2 * math.pi * math.e) * math.exp(2 * logdet / d)


def improved(cur, patterns, ks):
    best = {}
    for p in sorted({q for pat in patterns for q in glob.glob(os.path.join(HERE, pat), recursive=True)}):
        for s in read_solutions(p):
            if s.k in ks and s.m <= 16 and s.is_valid() and ((s.k, s.m) not in best or s.n < best[(s.k, s.m)]):
                best[(s.k, s.m)] = s.n
    return {k: sum(1 for m in range(1, 17) if cur.get(k, m) is not None and (k, m) in best
                   and best[(k, m)] < cur.get(k, m)) for k in ks}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-N", type=int, default=100)
    a = ap.parse_args()
    N = a.N
    cur = load_current("normal")
    ks = [k for k in range(33, 101)]
    search = improved(cur, ["results/turing/cpu/*-N100.txt", "results/turing/t4/*-N100.txt"], ks)
    allres = improved(cur, ["results/**/*.txt", "results/**/*.log"], ks)
    rows = []
    for k in ks:
        T = math.sqrt(N * gh2(k, N))
        r, j = max((math.log10(M(k, j) / (T * N**j)), j) for j in range(1, min(k, 12)))
        cells = sum(1 for m in range(1, 17) if cur.get(k, m) is not None)
        rows.append((k, j, r, search[k], allres[k], cells))
    strong = [row for row in rows if row[2] > -1]
    # the table: powers whose short relations have a forced moment (tools/forcedmoments.py,
    # BKZ-20 rows of L_{k,100}), with the fraction of rows on which it vanishes
    import json
    fm = json.load(open(os.path.join(HERE, "paper/data/forcedmoments.json")))
    forced = {int(kk): v["100"] for kk, v in fm.items() if v.get("100")}
    with open(os.path.join(HERE, "paper/tables/congruence.tex"), "w") as f:
        f.write("% generated by tools/congruence.py -- do not edit\n")
        f.write("\\begin{tabular}{rrlrrr}\n\\toprule\n$k$ & $j$ & primes $\\ell$ with $(\\ell-1)\\mid(k-j)$ & "
                "vanishes & plain & all \\\\\n\\midrule\n")
        for k in sorted(forced):
            if k < 33:
                continue
            j, mj, z = forced[k][0]
            ps = ", ".join(str(p) for p in PRIMES if (k - j) % (p - 1) == 0)
            c = sum(1 for m in range(1, 17) if cur.get(k, m) is not None)
            f.write(f"{k} & {j} & {ps} & {100 * z:.0f}\\% & {search[k]}/{c} & {allres[k]}/{c} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    fk = [k for k in forced if k >= 33]
    with open(os.path.join(HERE, "paper/tables/congnumbers.tex"), "w") as f:
        f.write("% generated by tools/congruence.py -- do not edit\n")
        f.write(f"\\newcommand{{\\ForcedK}}{{{len(fk)}}}\n")
        f.write(f"\\newcommand{{\\ForcedSieveImp}}{{{sum(search[k] for k in fk)}}}\n")
        f.write(f"\\newcommand{{\\ForcedAllImp}}{{{sum(allres[k] for k in fk)}}}\n")
        f.write(f"\\newcommand{{\\ForcedCells}}{{{sum(sum(1 for m in range(1, 17) if cur.get(k, m) is not None) for k in fk)}}}\n")
        nf = [k for k in ks if k not in forced]
        f.write(f"\\newcommand{{\\UnforcedK}}{{{len(nf)}}}\n")
        f.write(f"\\newcommand{{\\UnforcedSieveImp}}{{{sum(search[k] for k in nf)}}}\n")
        f.write(f"\\newcommand{{\\UnforcedCells}}{{{sum(sum(1 for m in range(1, 17) if cur.get(k, m) is not None) for k in nf)}}}\n")
        f.write(f"\\newcommand{{\\ForcedMainK}}{{{', '.join(str(k) for k in sorted(forced) if k < 33)}}}\n")
    return
    weak = [row for row in rows if row[2] <= -1]
    with open(os.path.join(HERE, "paper/tables/congnumbers.tex"), "w") as f:
        f.write("% generated by tools/congruence.py -- do not edit\n")
        f.write(f"\\newcommand{{\\CongStrongK}}{{{len(strong)}}}\n")
        f.write(f"\\newcommand{{\\CongStrongImp}}{{{sum(r[3] for r in strong)}}}\n")
        f.write(f"\\newcommand{{\\CongStrongCells}}{{{sum(r[5] for r in strong)}}}\n")
        f.write(f"\\newcommand{{\\CongWeakK}}{{{len(weak)}}}\n")
        f.write(f"\\newcommand{{\\CongWeakImp}}{{{sum(r[3] for r in weak)}}}\n")
        f.write(f"\\newcommand{{\\CongWeakCells}}{{{sum(r[5] for r in weak)}}}\n")
    for k, j, r, s1, s2, c in rows:
        flag = "*" if r > -1 else " "
        print(f"{flag} k={k:3d} j={j:2d} log10 r={r:+.2f} improved sieve {s1:2d}/{c} all {s2:2d}/{c}")


if __name__ == "__main__":
    main()
